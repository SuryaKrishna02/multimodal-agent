"""The eval pattern, shared by every component.

Each evals/<component>/eval.py defines:
    LEVEL       "component" or "end-to-end"
    USES_LLM    True if results depend on the model tier (E4B vs E2B)
    BUILTIN     optional; True if the eval builds its own cases in code (no case files)
    load_cases(cases_dir) -> list of items        (raises NoCases if the folder has none)
    run_item(item)        -> record dict          (one input -> one output, shown in live mode)
    score(records)        -> {metric: value}

Cases come from two folders per component:
    data/evals/synthetic/<component>/   generated by evals/synthetic.py, rebuilt on demand
    data/evals/user/<component>/        added by you with `python cli.py evals add`
run() runs both, tags each record with its source, and caches the result in
evals/results/<tier>/<component>.json, so the scorecard can be shown instantly.
"""

import importlib
import json
import time
from collections import Counter
from pathlib import Path

from agent import config
from agent.platforms.base import Unsupported

COMPONENTS = ["serving", "vad", "asr", "screen", "structured", "tool_calls", "memory", "tools", "task1", "task2"]


class NoCases(Exception):
    """This component has no eval cases, for example because synthetic audio needs a speech plug-in."""


def module(component: str):
    """Import the eval module of a component.

    Args:
        component (str): One of COMPONENTS.

    Returns:
        module: The module `evals.<component>.eval`.
    """
    return importlib.import_module(f"evals.{component}.eval")


def _tier_dir(mod) -> str:
    return config.TIER if mod.USES_LLM else "any"


def _start_servers(mod) -> None:
    from agent import serving

    if getattr(mod, "NEEDS_LLM_SERVER", mod.USES_LLM):
        serving.llm_server().start()
    if getattr(mod, "NEEDS_EMBED_SERVER", False):
        serving.embed_server().start()


def case_folders(component: str, mod, cases_dir: Path | None = None) -> list[tuple[str, Path]]:
    """List the folders that hold the cases of a component.

    Args:
        component (str): One of COMPONENTS.
        mod (module): The eval module of the component.
        cases_dir (Path, optional): Use only this folder (with a `<component>` folder inside). Defaults to None.

    Returns:
        list[tuple[str, Path]]: (source name, folder) pairs, synthetic first.
    """
    if cases_dir:
        return [("custom", cases_dir / component)]
    if getattr(mod, "BUILTIN", False):
        return [("builtin", config.EVAL_DATA / component)]
    return [("synthetic", config.EVAL_SYNTHETIC / component), ("user", config.EVAL_USER / component)]


def _load(mod, folder: Path) -> list:
    """Load the cases of one folder, or an empty list when the folder has none."""
    try:
        return mod.load_cases(folder)
    except NoCases:
        return []


def _ensure_synthetic(component: str, mod, cases_dir: Path | None) -> str | None:
    """Build the synthetic cases if they are missing or outdated.

    Returns:
        str | None: Why they could not be built (the platform lacks a hook), else None.
    """
    if cases_dir or getattr(mod, "BUILTIN", False):
        return None
    from evals import synthetic

    try:
        synthetic.ensure(component)
    except Unsupported as e:
        return str(e)
    return None


def _run_sources(mod, folders, limit: int | None, verbose: bool) -> list[dict]:
    """Run the cases of every source in turn. Each source is loaded just before it runs."""
    records: list[dict] = []
    started = False
    for source, folder in folders:
        items = _load(mod, folder)
        if items and not started:
            _start_servers(mod)  # only when there is something to run
            started = True
        for item in items[: None if limit is None else max(limit - len(records), 0)]:
            t_item = time.time()
            rec = {**mod.run_item(item), "source": source, "seconds": round(time.time() - t_item, 2)}
            records.append(rec)
            if verbose:
                print(f"  [{len(records)}] {json.dumps(rec, default=str)[:160]}")
    return records


def run(component: str, cases_dir: Path | None = None, limit: int | None = None, verbose: bool = False) -> dict:
    """Run one eval over its synthetic and user cases, cache the result and return it.

    Args:
        component (str): One of COMPONENTS.
        cases_dir (Path, optional): Run only the cases in this folder. Defaults to the synthetic and user folders.
        limit (int, optional): Run only the first cases. Defaults to None.
        verbose (bool, optional): Print each record as it finishes. Defaults to False.

    Returns:
        dict: `component`, `level`, `tier`, `n`, `sources`, `metrics`, `by_source`, `seconds`, `when` and `records`.

    Raises:
        NoCases: If the component has no cases.
    """
    mod = module(component)
    reason = _ensure_synthetic(component, mod, cases_dir)
    folders = case_folders(component, mod, cases_dir)
    t0 = time.time()
    records = _run_sources(mod, folders, limit, verbose)
    if not records:
        raise NoCases(reason or f"no cases for {component} in {', '.join(str(f) for _, f in folders)}")
    sources = dict(Counter(r["source"] for r in records))
    result = {
        "component": component,
        "level": mod.LEVEL,
        "tier": _tier_dir(mod),
        "n": len(records),
        "sources": sources,
        "metrics": mod.score(records),
        "by_source": {s: mod.score([r for r in records if r["source"] == s]) for s in sources}
        if len(sources) > 1
        else {},
        "seconds": round(time.time() - t0, 1),
        "when": time.strftime("%Y-%m-%d %H:%M"),
        "records": records,
    }
    out = config.RESULTS / result["tier"] / f"{component}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=1, default=str))
    return result


def run_live(component: str, n: int = 1, cases_dir: Path | None = None) -> list[dict]:
    """Run a few cases with visible inputs and outputs. Not cached.

    Args:
        component (str): One of COMPONENTS.
        n (int, optional): How many cases to run. Defaults to 1.
        cases_dir (Path, optional): Run only the cases in this folder. Defaults to None.

    Returns:
        list[dict]: One record per case.

    Raises:
        NoCases: If the component has no cases.
    """
    mod = module(component)
    reason = _ensure_synthetic(component, mod, cases_dir)
    for source, folder in case_folders(component, mod, cases_dir):
        if items := _load(mod, folder)[:n]:
            _start_servers(mod)
            return [{**mod.run_item(item), "source": source} for item in items]
    raise NoCases(reason or f"no cases for {component}")


def case_counts(component: str) -> dict[str, int]:
    """Count the cases of each source without running them.

    Args:
        component (str): One of COMPONENTS.

    Returns:
        dict[str, int]: Source name to number of cases. A folder that does not exist counts 0.
    """
    mod = module(component)
    return {s: len(_load(mod, f)) if f.is_dir() else 0 for s, f in case_folders(component, mod)}


def passes(metric_key: str, value) -> bool | None:
    """Check a metric value against its threshold.

    Args:
        metric_key (str): "<component>.<metric>", the key in `config.THRESHOLDS`.
        value: The measured value, or None.

    Returns:
        bool | None: Whether the value passes, or None if there is no threshold or no value.
    """
    if metric_key not in config.THRESHOLDS or value is None:
        return None
    op, threshold = config.THRESHOLDS[metric_key]
    return value <= threshold if op == "<=" else value >= threshold


def cached_results(component: str, mod) -> dict[str, dict]:
    """Load the cached result file of `component` for each tier that has one.

    Args:
        component (str): One of COMPONENTS.
        mod (module): The eval module of the component.

    Returns:
        dict[str, dict]: Tier name to the result that `run` cached.
    """
    tiers = list(config.TIERS) if mod.USES_LLM else ["any"]
    files = {t: config.RESULTS / t / f"{component}.json" for t in tiers}
    return {t: json.loads(f.read_text()) for t, f in files.items() if f.exists()}


def _metric_row(component: str, level: str, metric: str, cached: dict[str, dict]) -> dict:
    """Build the scorecard row of one metric, with a cell for each cached tier."""
    key = f"{component}.{metric}"
    row: dict = {
        "component": component,
        "level": level,
        "metric": metric,
        "threshold": " ".join(map(str, config.THRESHOLDS[key])) if key in config.THRESHOLDS else "",
    }
    for t, r in cached.items():
        v = r["metrics"].get(metric)
        row[t] = {"value": v, "pass": passes(key, v), "n": r["n"], "sources": r.get("sources", {}), "when": r["when"]}
    return row


def scorecard_rows() -> list[dict]:
    """One row per (component, metric), with a column per tier found in the cache."""
    rows = []
    for component in COMPONENTS:
        mod = module(component)
        cached = cached_results(component, mod)
        if not cached:
            rows.append({"component": component, "level": mod.LEVEL, "metric": "-", "status": "not run"})
            continue
        metrics = sorted({m for r in cached.values() for m in r["metrics"]})
        rows.extend(_metric_row(component, mod.LEVEL, m, cached) for m in metrics)
    return rows


def _scorecard_cell(cell: dict | None) -> str:
    """Format one tier cell of the scorecard to 16 characters, blank when the tier has no result."""
    if not cell:
        return f"{'':>16s}"
    v = cell["value"]
    mark = {True: "PASS", False: "FAIL", None: ""}[cell["pass"]]
    vs = f"{v:.3f}" if isinstance(v, float) else str(v)
    return f"{vs + ' ' + mark:>16s}"


def print_scorecard() -> None:
    """Print the cached results as a table, grouped by component level."""
    rows = scorecard_rows()
    tiers = ["any", *config.TIERS]
    print(f"\n{'level':11s} {'component':11s} {'metric':24s} {'threshold':10s} " + " ".join(f"{t:>16s}" for t in tiers))
    print("-" * (60 + 17 * len(tiers)))
    for level in ("component", "end-to-end"):
        for r in [r for r in rows if r["level"] == level]:
            cells = " ".join(_scorecard_cell(r.get(t)) for t in tiers)
            print(
                f"{level:11s} {r['component']:11s} {r['metric']:24s} {r.get('threshold', ''):10s} "
                + (cells if r.get("status") != "not run" else "   (not run: python cli.py evals --run)")
            )
    print()
